@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun BulkPropertiesSheet(
    nodes: List<StorageNode>,
    onDismiss: () -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)

    var totalBytes by remember { mutableStateOf(0L) }
    var totalNestedFiles by remember { mutableStateOf(0) }
    var totalNestedFolders by remember { mutableStateOf(0) }
    var isCalculating by remember { mutableStateOf(false) }

    val directFolderCount = nodes.count { it.isDirectory }
    val directFileCount = nodes.count { !it.isDirectory }
    val commonParent = remember(nodes) {
        if (nodes.isEmpty()) "" else File(nodes.first().path).parent ?: "/"
    }

    LaunchedEffect(nodes) {
        isCalculating = true
        var bytes = 0L
        var nestedFiles = 0
        var nestedFolders = 0

        for (node in nodes) {
            if (node.isDirectory) {
                val details = FolderDetailsCalculator.calculateDetails(File(node.path))
                bytes += details.totalBytes
                nestedFiles += details.totalFiles.toInt()
                nestedFolders += (details.totalFolders.toInt() + 1)
            } else {
                bytes += node.size
                nestedFiles += 1
            }
        }

        totalBytes = bytes
        totalNestedFiles = nestedFiles
        totalNestedFolders = nestedFolders
        isCalculating = false
    }

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        modifier = modifier
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 20.dp, vertical = 12.dp)
                .verticalScroll(rememberScrollState())
        ) {
            // Header
            Row(
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier.fillMaxWidth()
            ) {
                Box(
                    modifier = Modifier
                        .size(44.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.primaryContainer),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = Icons.Default.FolderCopy,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.onPrimaryContainer,
                        modifier = Modifier.size(24.dp)
                    )
                }

                Spacer(modifier = Modifier.width(14.dp))

                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "${nodes.size} Selected Items",
                        style = MaterialTheme.typography.titleLarge,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = "$directFileCount files, $directFolderCount folders",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))
            HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant.copy(alpha = 0.5f))
            Spacer(modifier = Modifier.height(12.dp))

            // Total Size
            PropertyRow(
                label = "Total Size",
                value = if (isCalculating) "Calculating..."
                else "${FileFormatter.formatFileSize(totalBytes)} (${FileFormatter.formatExactBytes(totalBytes)})"
            )

            // Contains
            if (directFolderCount > 0) {
                PropertyRow(
                    label = "Contains",
                    value = if (isCalculating) "Scanning contents..."
                    else "$totalNestedFiles files, $totalNestedFolders folders"
                )
            }

            // Location
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(8.dp))
                    .clickable {
                        copyToClipboard(context, "Location", commonParent)
                    }
                    .padding(vertical = 8.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "Location",
                        style = MaterialTheme.typography.labelMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Spacer(modifier = Modifier.height(2.dp))
                    Text(
                        text = commonParent,
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurface,
                        maxLines = 2,
                        overflow = TextOverflow.Ellipsis
                    )
                }
                IconButton(onClick = { copyToClipboard(context, "Location", commonParent) }) {
                    Icon(
                        imageVector = Icons.Default.ContentCopy,
                        contentDescription = "Copy Location",
                        tint = MaterialTheme.colorScheme.primary,
                        modifier = Modifier.size(18.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(24.dp))
        }
    }
}

@Composable
private fun PropertyRow(
    label: String,
    value: String,
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxWidth()
            .padding(vertical = 8.dp)
    ) {
        Text(
            text = label,
            style = MaterialTheme.typography.labelMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
        Spacer(modifier = Modifier.height(2.dp))
        Text(
            text = value,
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurface,
            fontWeight = FontWeight.Medium
        )
    }
}

private fun copyToClipboard(context: Context, label: String, text: String) {
    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
    val clip = ClipData.newPlainText(label, text)
    clipboard.setPrimaryClip(clip)
    Toast.makeText(context, "$label copied to clipboard", Toast.LENGTH_SHORT).show()
}
